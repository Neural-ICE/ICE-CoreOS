//! End-to-end CLI tests against the built binary.
//!
//! Most fixtures carry no key material at all -- they are canonical documents
//! whose BINDINGS are the thing under test -- so `NI_OTA_COSIGN` injects a stub
//! whose verdict is driven by the CONTENT of the signature file (`GOOD` accepts
//! a fixture; `SHA256:<digest>` binds it to the exact blob). That keeps every §0
//! check running through the real subprocess plumbing.
//!
//! 🔴 THE ACCESS-PROFILE ANCHOR IS THE EXCEPTION, and deliberately so. It used
//! to be built from `b"neural-ice-test-device-root-spki-der"` and an eight-byte
//! DER-shaped constant, so the suite proved the plumbing and nothing about the
//! cryptography: a broken domain separation, a broken canonical serialisation or
//! a broken r||s -> DER conversion all passed. The anchor fixture now uses a
//! REAL ECDSA P-256 key generated by openssl, a REAL signature over the exact
//! domain-separated payload, and the stub verifies it with REAL openssl. The
//! TPM is mocked -- a CI runner has none -- but the mock signs with that same
//! real key and emits the raw r||s form a TPM emits, so the liveness challenge
//! exercises production code end to end.
