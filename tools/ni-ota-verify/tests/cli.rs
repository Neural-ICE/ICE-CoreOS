struct Fixture {
    dir: PathBuf,
}

/// The ways an access-profile anchor can be wrong on a real appliance, each of
/// which must be a refusal rather than a default.
#[derive(Clone, Copy, PartialEq, Eq)]
enum AnchorDefect {
    None,
    /// Signed by a device root that is not this machine's -- an anchor lifted
    /// from another appliance, whose signature is perfectly valid.
    ForeignDeviceRoot,
    /// Same fields, different key order: a second way to write the document,
    /// and therefore a second document.
    NonCanonical,
    /// A perfectly signed, live, current anchor whose profile is NOT the one this
    /// machine's write-once TPM record binds -- i.e. exactly what a privileged
    /// runtime attacker produces with the empty-policy device root.
    ForeignProfileBinding,
}

/// The digest that binds an appliance's access profile, hardware target and
/// Secure Boot trust policy, computed the way `ota/neural-ice-tpm-state.sh` and
/// `src/access_profile_anchor.rs` both compute it. Written out here a third time
/// ON PURPOSE: a fixture that called the implementation would agree with it
/// whatever it did.
fn profile_binding_digest(profile: &str, target: &str, policy_id: &str) -> String {
    let mut bytes = b"neural-ice:tpm:access-profile-binding:v1".to_vec();
    bytes.push(0);
    bytes.extend_from_slice(profile.as_bytes());
    bytes.push(0);
    bytes.extend_from_slice(target.as_bytes());
    bytes.push(0);
    bytes.extend_from_slice(policy_id.as_bytes());
    sha256_of_bytes(&bytes)
}

