fn run(cmd: &mut Command) -> (i32, Value, String) {
    let out = cmd.output().expect("binary runs");
    let code = out.status.code().expect("exit code");
    let stdout = String::from_utf8(out.stdout).unwrap();
    let verdict = stdout.lines().next().map_or(Value::Null, |line| {
        serde_json::from_str(line).expect("stdout line 1 is the JSON verdict")
    });
    (
        code,
        verdict,
        String::from_utf8_lossy(&out.stderr).into_owned(),
    )
}

fn check<'v>(verdict: &'v Value, name: &str) -> &'v Value {
    verdict["checks"]
        .as_array()
        .expect("checks array")
        .iter()
        .find(|c| c["name"] == name)
        .unwrap_or_else(|| panic!("check '{name}' missing from {verdict}"))
}

fn sha256_of(path: &Path) -> String {
    let out = Command::new("sha256sum").arg(path).output().unwrap();
    String::from_utf8(out.stdout)
        .unwrap()
        .split_whitespace()
        .next()
        .unwrap()
        .to_string()
}

/// Same shelling-out shape as `sha256_of`, for bytes that never hit the disk.
/// ECDSA over P-256 admits two signatures for one message: `(r, s)` and
/// `(r, n - s)`. The OTA contract accepts only the canonical LOW-S form, so a
/// fixture that did not normalise would fail roughly every other run for a
/// reason that has nothing to do with the code under test.
fn normalise_low_s(der: &Path) {
    let script = r#"
import sys
ORDER = 0xFFFFFFFF00000000FFFFFFFFFFFFFFFFBCE6FAADA7179E84F3B9CAC2FC632551
raw = open(sys.argv[1], "rb").read()
assert raw[0] == 0x30
body = raw[2:2 + raw[1]]
def take(buf):
    assert buf[0] == 0x02
    length = buf[1]
    return int.from_bytes(buf[2:2 + length], "big"), buf[2 + length:]
r, rest = take(body)
s, _ = take(rest)
if s > ORDER // 2:
    s = ORDER - s
def integer(value):
    encoded = value.to_bytes((value.bit_length() + 8) // 8 or 1, "big")
    return b"\x02" + bytes([len(encoded)]) + encoded
out = integer(r) + integer(s)
open(sys.argv[1], "wb").write(b"\x30" + bytes([len(out)]) + out)
"#;
    let output = Command::new("python3")
        .arg("-c")
        .arg(script)
        .arg(der)
        .output()
        .unwrap();
    assert!(
        output.status.success(),
        "low-S normalisation failed: {}",
        String::from_utf8_lossy(&output.stderr)
    );
}

